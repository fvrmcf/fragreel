import { HighlightClip, ParsedDemo, PlayerPath, TeamSide } from '../types/demo';

function angleBetween(x1: number, y1: number, x2: number, y2: number): number {
  return Math.atan2(y2 - y1, x2 - x1);
}

/**
 * Helper that builds realistic synchronized paths for the star player and all victims
 * so every highlight clip plays smoothly with accurate movement, aim tracking, and death markers.
 */
function buildPathsFromKills(
  starName: string,
  starTeam: TeamSide,
  kills: HighlightClip['kills'],
  durationSec: number,
  extraTeammates?: { name: string; team: TeamSide; pos: [number, number] }[]
): PlayerPath[] {
  const starWaypoints: PlayerPath['waypoints'] = [];
  if (kills.length > 0) {
    const first = kills[0];
    starWaypoints.push({
      time: 0,
      x: Math.max(80, Math.min(920, first.attackerPos[0] - 28)),
      y: Math.max(80, Math.min(920, first.attackerPos[1] + 22)),
      angle: angleBetween(first.attackerPos[0], first.attackerPos[1], first.victimPos[0], first.victimPos[1]),
      alive: true,
      hp: 100,
    });

    let hp = 100;
    kills.forEach((k, idx) => {
      const aimAngle = angleBetween(k.attackerPos[0], k.attackerPos[1], k.victimPos[0], k.victimPos[1]);
      if (idx > 0) {
        hp = Math.max(14, hp - (idx % 2 === 0 ? 22 : 12));
      }
      starWaypoints.push({
        time: Math.max(0.25, k.timeOffset - 0.35),
        x: k.attackerPos[0],
        y: k.attackerPos[1],
        angle: aimAngle,
        alive: true,
        hp,
      });
      starWaypoints.push({
        time: k.timeOffset + 0.12,
        x: k.attackerPos[0] + (idx % 2 === 0 ? 5 : -5),
        y: k.attackerPos[1] + (idx % 2 === 0 ? -4 : 4),
        angle: aimAngle,
        alive: true,
        hp,
      });
    });

    const last = kills[kills.length - 1];
    starWaypoints.push({
      time: durationSec + 5,
      x: last.attackerPos[0] + 18,
      y: last.attackerPos[1] - 12,
      angle: angleBetween(last.attackerPos[0], last.attackerPos[1], last.victimPos[0], last.victimPos[1]),
      alive: true,
      hp,
    });
  }

  const paths: PlayerPath[] = [
    {
      playerName: starName,
      team: starTeam,
      isStar: true,
      waypoints: starWaypoints,
    },
  ];

  // Build victim approaches that converge on their death position right at kill time
  kills.forEach((k, idx) => {
    const dx = k.victimPos[0] - k.attackerPos[0];
    const dy = k.victimPos[1] - k.attackerPos[1];
    const len = Math.hypot(dx, dy) || 1;
    const approachX = Math.max(90, Math.min(910, k.victimPos[0] + (dx / len) * 68 + (idx % 2 === 0 ? 24 : -24)));
    const approachY = Math.max(90, Math.min(910, k.victimPos[1] + (dy / len) * 68 + (idx % 2 === 0 ? -18 : 22)));
    const faceStar = angleBetween(k.victimPos[0], k.victimPos[1], k.attackerPos[0], k.attackerPos[1]);

    paths.push({
      playerName: k.victimName,
      team: k.victimTeam,
      isStar: false,
      waypoints: [
        { time: 0, x: approachX, y: approachY, angle: faceStar, alive: true, hp: 100 },
        {
          time: Math.max(0.1, k.timeOffset - 0.15),
          x: k.victimPos[0],
          y: k.victimPos[1],
          angle: faceStar,
          alive: true,
          hp: 100,
        },
        {
          time: k.timeOffset,
          x: k.victimPos[0],
          y: k.victimPos[1],
          angle: faceStar,
          alive: false,
          hp: 0,
        },
      ],
    });
  });

  if (extraTeammates) {
    extraTeammates.forEach((mate) => {
      paths.push({
        playerName: mate.name,
        team: mate.team,
        isStar: false,
        waypoints: [
          { time: 0, x: mate.pos[0], y: mate.pos[1], angle: -0.6, alive: true, hp: 100 },
          { time: durationSec + 4, x: mate.pos[0] + 16, y: mate.pos[1] - 10, angle: -0.3, alive: true, hp: 82 },
        ],
      });
    });
  }

  return paths;
}

